package db;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;

public class DBCreateTables {
    private static Statement statement;
    private static PreparedStatement preparedStatement;

    public static void initializeDatabase() {
        Connection connection = DBConnectionManager.getInstance().get();

        try {
            initializeSchema(connection);
            initializeTables(connection);
            initializeData(connection);

        } catch (SQLException e) {
            throw new RuntimeException(e);
        } finally {
            try {
                if (statement != null)
                    statement.close();
                if (preparedStatement != null)
                    preparedStatement.close();
                DBConnectionManager.getInstance().disconnect(connection);
            } catch (SQLException e) {
                throw new RuntimeException(e);
            }
        }
    }

    private static void initializeData(Connection connection) throws SQLException {
        statement = connection.createStatement();
        statement.executeUpdate("DELETE FROM banking.Transaction");
        statement.executeUpdate("DELETE FROM banking.BankAccount");
        statement.executeUpdate("DELETE FROM banking.User");
        statement.close();

        preparedStatement = connection.prepareStatement(
                "INSERT INTO banking.User (name, email, phone, id) VALUES (?, ?, ?, ?)"
        );

        preparedStatement.setString(1, "Иван");
        preparedStatement.setString(2, "ivan@mail.ru");
        preparedStatement.setString(3, "+79999999999");
        preparedStatement.setString(4, "1");
        preparedStatement.executeUpdate();

        preparedStatement.setString(1, "Алексей");
        preparedStatement.setString(2, "alex@mail.ru");
        preparedStatement.setString(3, "+78888888888");
        preparedStatement.setString(4, "2");
        preparedStatement.executeUpdate();

        preparedStatement.close();

        preparedStatement = connection.prepareStatement(
                "INSERT INTO banking.BankAccount (user_id, number, balance) VALUES (?, ?, ?)"
        );

        preparedStatement.setString(1, "1");
        preparedStatement.setString(2, "11111");
        preparedStatement.setDouble(3, 100.00);
        preparedStatement.executeUpdate();

        preparedStatement.setString(1, "1");
        preparedStatement.setString(2, "22222");
        preparedStatement.setDouble(3, 200.00);
        preparedStatement.executeUpdate();

        preparedStatement.setString(1, "2");
        preparedStatement.setString(2, "33333");
        preparedStatement.setDouble(3, 300.00);
        preparedStatement.executeUpdate();

        preparedStatement.setString(1, "2");
        preparedStatement.setString(2, "44444");
        preparedStatement.setDouble(3, 400.00);
        preparedStatement.executeUpdate();

        preparedStatement.close();

    }

    private static void initializeTables(Connection connection) throws SQLException {
        statement = connection.createStatement();

        statement.executeUpdate(
                "CREATE TABLE IF NOT EXISTS banking.User (" +
                        "id VARCHAR(50) PRIMARY KEY, " +
                        "name VARCHAR(100) NOT NULL, " +
                        "email VARCHAR(100) NOT NULL UNIQUE, " +
                        "phone VARCHAR(20) UNIQUE)"
        );
        statement.executeUpdate(
                "CREATE TABLE IF NOT EXISTS banking.BankAccount (" +
                        "user_id VARCHAR(50) NOT NULL, " +
                        "number VARCHAR(50) PRIMARY KEY, " +
                        "balance DECIMAL(15,2) DEFAULT 0.00, " +
                        "FOREIGN KEY (user_id) REFERENCES banking.User(id) ON DELETE CASCADE)"
        );
        statement.executeUpdate(
                "CREATE TABLE IF NOT EXISTS banking.Transaction (" +
                        "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                        "user_id VARCHAR(50) NOT NULL, " +
                        "amount DECIMAL(15,2) NOT NULL, " +
                        "type VARCHAR(20) NOT NULL, " +
                        "date TIMESTAMP DEFAULT CURRENT_TIMESTAMP, " +
                        "source VARCHAR(50), " +
                        "target VARCHAR(50) NOT NULL, " +
                        "FOREIGN KEY (user_id) REFERENCES banking.User(id) ON DELETE CASCADE, " +
                        "FOREIGN KEY (target) REFERENCES banking.User(id) ON DELETE SET NULL)"
        );

        statement.close();
    }

    private static void initializeSchema(Connection connection) throws SQLException {
        statement = connection.createStatement();
        statement.executeUpdate("CREATE SCHEMA IF NOT EXISTS banking;");
        statement.close();
    }
}
